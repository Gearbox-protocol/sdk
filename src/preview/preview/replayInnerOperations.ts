import type { OperationPreviewError } from "../../model/index.js";
import {
  AbstractAdapterContract,
  AssetsMap,
  MAX_UINT256,
  type OnchainSDK,
  type PluginsMap,
} from "../../onchain/index.js";
import type {
  AdapterOperation,
  AddCollateralOp,
  InnerOperation,
  WithdrawCollateralOp,
} from "../parse/index.js";
import type { CreditAccountState } from "./CreditAccountState.js";
import {
  adapterCallOutsideBracketError,
  malformedBracketError,
  nonAdapterCallInBracketError,
  unpreviewableAdapterCallError,
  unsupportedOutOfBracketCallError,
} from "./errors.js";

/**
 * Running state threaded through a credit-facade multicall by
 * {@link replayInnerOperations}: the account's post-state being mutated in
 * facade execution order, plus per-multicall bookkeeping that is not account
 * state (what was added from / withdrawn to the wallet).
 */
export interface ReplayState {
  /**
   * Running account state, mutated in facade execution order. Seeded by the
   * caller: `CreditAccountState.beforeOpen` for account opening, a clone of
   * `CreditAccountState.fromCreditAccountData` for an existing account.
   */
  account: CreditAccountState;
  /**
   * Cumulative amounts added via `addCollateral`.
   */
  collateralAdded: AssetsMap;
  /**
   * Cumulative amounts withdrawn via `withdrawCollateral`, with `MAX_UINT256`
   * resolved against the running balance at the point of the call.
   */
  collateralWithdrawn: AssetsMap;
}

/**
 * Creates a {@link ReplayState} around the given account seed, with empty
 * bookkeeping.
 */
export function makeReplayState(account: CreditAccountState): ReplayState {
  return {
    account,
    collateralAdded: new AssetsMap(),
    collateralWithdrawn: new AssetsMap(),
  };
}

/**
 * Replays a credit-facade multicall over `state`, mutating it in place in
 * facade execution order. The result is the *minimal guaranteed* post-state.
 *
 * The function assumes that the call was generated by our frontend using
 * router/withdrawal compressor, otherwise it returns a warning, but still
 * proceeds best-effort.
 *
 * @returns `undefined` on success, the warning on a malformed multicall.
 */
export function replayInnerOperations<P extends PluginsMap>(
  sdk: OnchainSDK<P>,
  multicall: InnerOperation[],
  state: ReplayState,
): OperationPreviewError | undefined {
  // True between `StoreExpectedBalances` and `CompareBalances`
  let inBracket = false;
  let warning: OperationPreviewError | undefined;

  for (const op of multicall) {
    let opWarning: OperationPreviewError | undefined;

    switch (op.operation) {
      case "AddCollateral":
        applyAddCollateral(state, op);
        break;
      case "WithdrawCollateral":
        applyWithdrawCollateral(state, op);
        break;
      case "IncreaseBorrowedAmount":
        state.account.increaseDebt(op.amount);
        break;
      case "DecreaseBorrowedAmount":
        state.account.repay(op.amount);
        break;
      case "UpdateQuota":
        state.account.updateQuota(op.token, op.change);
        break;
      case "StoreExpectedBalances":
        if (inBracket) {
          opWarning = malformedBracketError("nested");
        }
        inBracket = true;
        // StoreExpectedBalances applies deltas to "tokens out"
        for (const { token, balance } of op.deltas) {
          state.account.balances.inc(token, balance);
        }
        break;
      case "CompareBalances":
        if (!inBracket) {
          opWarning = malformedBracketError("unmatchedCompare");
        }
        inBracket = false;
        break;
      case "Execute":
        opWarning = applyExecute(sdk, op, inBracket, state.account.balances);
        break;
    }

    // save warning, but continue
    warning ??= opWarning;
  }

  if (inBracket) {
    // The router always emits storeExpectedBalances/compareBalances as a pair
    warning ??= malformedBracketError("unmatchedStore");
  }

  return warning;
}

function applyAddCollateral(state: ReplayState, op: AddCollateralOp): void {
  state.collateralAdded.inc(op.token, op.amount);
  state.account.balances.inc(op.token, op.amount);
}

/**
 * `MAX_UINT256` is the facade sentinel for "withdraw the entire balance", so
 * it is resolved against the running balance at the point of the call.
 */
function applyWithdrawCollateral(
  state: ReplayState,
  op: WithdrawCollateralOp,
): void {
  const running = state.account.balances.getOrZero(op.token);
  const amount =
    op.amount === MAX_UINT256 ? (running > 0n ? running : 0n) : op.amount;
  state.account.balances.dec(op.token, amount);
  state.collateralWithdrawn.inc(op.token, amount);
}

/**
 * Replays an adapter `Execute` call against the running balances.
 *
 * Inside a bracket, the adapter's balance changes are previewed via
 * {@link AbstractAdapterContract.previewBalanceChanges}. Outside a bracket,
 * only calls that {@link AbstractAdapterContract.replayOutOfBracketCall}
 * accepts are allowed; nothing enforces the outcome of any other out-of-bracket
 * adapter call on-chain, so its effect on balances cannot be previewed.
 */
function applyExecute<P extends PluginsMap>(
  sdk: OnchainSDK<P>,
  op: AdapterOperation,
  inBracket: boolean,
  balances: AssetsMap,
): OperationPreviewError | undefined {
  const adapter = sdk.getContract(op.adapter);

  if (!inBracket) {
    if (adapter instanceof AbstractAdapterContract) {
      try {
        if (adapter.replayOutOfBracketCall(balances, op.calldata)) {
          return undefined;
        }
      } catch (e) {
        return unsupportedOutOfBracketCallError(op.adapter, e);
      }
    }
    return adapterCallOutsideBracketError(op.adapter);
  }

  // unknown adapter or Execute call to some contract that is genuinely not an adapter
  if (!(adapter instanceof AbstractAdapterContract)) {
    return nonAdapterCallInBracketError(op.adapter);
  }

  try {
    adapter.previewBalanceChanges(balances, op.calldata);
    return undefined;
  } catch (e) {
    return unpreviewableAdapterCallError(op.adapter, e);
  }
}
