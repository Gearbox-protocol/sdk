import type { Address } from "viem";
import type { Curator } from "./curators.js";
import type { ChainScopedFilter, Filterable } from "./filters.js";
import { isFilterSet } from "./filters.js";
import type {
  Amount,
  AssetType,
  Bps,
  ChainId,
  Leverage,
  Timestamp,
  Token,
} from "./primitives.js";

/**
 * Discriminator of the two opportunity kinds.
 *
 * - `"pool"` — passive lending: deposit the underlying, earn the supply rate.
 * - `"strategy"` — leveraged position: deposit collateral, borrow the
 *   underlying against it inside a credit account.
 **/
export type OpportunityKind = "pool" | "strategy";

/**
 * An off-chain points program a position accrues towards, e.g. a partner
 * protocol's season points. Points have no APY, so they are listed separately
 * from token rewards.
 **/
export interface PointsProgram {
  /**
   * Stable slug of the program.
   *
   * @example `"ethena-sats-s3"`
   **/
  id: string;
  /**
   * Display name of the program.
   *
   * @example `"Ethena Sats Season 3"`
   **/
  name: string;
  /**
   * Points earned per unit of position relative to the program's base rate, or
   * `null` when the program does not publish one.
   *
   * @example `2` for a 2x boost
   **/
  multiplier: number | null;
}

/**
 * Rewards paid out in a token, e.g. a liquidity mining program.
 **/
export interface TokenRewards {
  kind: "token";
  /**
   * Token the rewards are paid in.
   **/
  token: Token;
  /**
   * Extra APR earned by supplying, in basis points.
   *
   * @example `120` for +1.2% APR
   **/
  supplyApr?: Bps;
  /**
   * Extra APR earned on the borrowed side, in basis points. Present when a
   * program rebates part of the borrow cost.
   *
   * @example `45` for +0.45% APR
   **/
  borrowApr?: Bps;
}

/**
 * Rewards accrued as points rather than tokens.
 **/
export interface PointRewards {
  kind: "point";
  /**
   * Programs the position accrues points in.
   **/
  points: PointsProgram[];
}

/**
 * Any reward stream attached to an opportunity.
 **/
export type Rewards = TokenRewards | PointRewards;

/**
 * A yield figure split into the part the protocol itself generates and the
 * incentives layered on top.
 **/
export interface ApyBreakdown {
  /**
   * Everything combined, in basis points: the number a UI shows as "APY".
   *
   * Absent in `onchain` mode: it folds in the incentives of {@link rewards},
   * which only the backend knows.
   *
   * @example `842` for 8.42% APY
   *
   * @mode offchain
   **/
  totalApy?: Bps;
  /**
   * The part generated by the underlying protocol alone, without incentives,
   * in basis points. Always readable from the chain.
   *
   * @example `610` for 6.10% APY
   **/
  organicApy: Bps;
  /**
   * Incentives that make up the difference between {@link organicApy} and
   * {@link totalApy}, plus any points programs that carry no APY at all.
   *
   * @mode offchain
   **/
  rewards?: Rewards[];
}

/**
 * Fields both opportunity kinds share.
 **/
export interface OpportunityBase {
  /**
   * Chain the opportunity lives on.
   **/
  chainId: ChainId;
  /**
   * Human-readable name for the row.
   *
   * @example `"USDC Pool"`, `"wstETH / WETH"`
   **/
  name: string;
  /**
   * Curator of the market this opportunity belongs to.
   **/
  curator: Curator;
  /**
   * Token that is supplied to the pool and borrowed by credit accounts. All
   * amounts of the opportunity are denominated in it.
   *
   * For RWA markets it's an unwrapped, e.g. — `USDC`, not `dcUSDC` (pool underlying according to contract).
   * The wrapper converts one-for-one, so every amount stays exact.
   **/
  underlyingToken: Token;
  /**
   * Debt principal drawn against the opportunity: everything the pool has lent
   * out for a {@link PoolOpportunity} (`pool.totalBorrowed()`), only what the
   * strategy's credit manager has drawn for a {@link StrategyOpportunity}
   * (`pool.creditManagerBorrowed(creditManager)`).
   **/
  totalBorrow: Amount;
  /**
   * Tokens accepted as collateral, i.e. the tokens that have both a non-zero
   * liquidation threshold and a non-zero quota limit.
   **/
  collateralTokens: Token[];
  /**
   * The contract's own pause flag: the pool for a {@link PoolOpportunity}, the
   * credit facade or the pool it borrows from for a
   * {@link StrategyOpportunity}.
   **/
  paused: boolean;
  /**
   * Whether at least one of {@link collateralTokens} is a real-world-asset
   * token. Read from a hardcoded per-chain list rather than from the chain.
   **/
  rwa: boolean;
  /**
   * Whether the opportunity is being wound down and should no longer be
   * entered. Read from a hardcoded per-chain list, kept separately for pools
   * and for strategies, and unrelated to
   * {@link StrategyOpportunity.expirationDate}.
   **/
  sunset: boolean;
}

/**
 * Passive lending into a Gearbox pool.
 *
 * Identified by `(chainId, pool)`, see {@link poolOpportunityId}.
 **/
export interface PoolOpportunity extends OpportunityBase {
  kind: "pool";
  /**
   * Address of the ERC-4626 pool contract.
   **/
  pool: Address;
  /**
   * Size of the pool: the underlying its shares are worth, converted at the
   * current share rate, i.e. `pool.totalAssets()`. Denominated in the
   * underlying rather than in shares, so it is comparable with
   * {@link OpportunityBase.totalBorrow}.
   **/
  totalSupply: Amount;
  /**
   * Pool available liquidity. Denominated in the underlying.
   **/
  availableLiquidity: Amount;
  /**
   * How much of the pool's capital is currently borrowed, in basis points.
   *
   * @example `7500` for 75% utilization
   **/
  utilization: Bps;
  /**
   * Yield earned by supplying to the pool.
   *
   * Its {@link ApyBreakdown.organicApy} is the pool's own supply rate (
   * which consists of base interest and quota revenue)
   * so this group is present in `onchain` mode too, with only that part filled.
   **/
  supplyApy: ApyBreakdown;
  /**
   * Average {@link supplyApy} over the trailing seven days.
   *
   * Absent in `onchain` mode: calculating it requires historical data.
   *
   * @mode offchain
   **/
  supplyApyAvg7D?: ApyBreakdown;
}

/**
 * A leveraged position: one credit manager plus one target collateral token.
 * A credit manager that accepts five collateral tokens therefore produces five
 * strategies.
 *
 * Identified by `(chainId, creditManager, targetCollateral.address)`,
 * see {@link strategyOpportunityId}.
 **/
export interface StrategyOpportunity extends OpportunityBase {
  kind: "strategy";
  /**
   * Address of the credit manager the position is opened in.
   **/
  creditManager: Address;
  /**
   * Collateral token the position is built around.
   **/
  targetCollateral: Token;
  /**
   * Liquidation threshold of {@link targetCollateral} in this credit manager,
   * in basis points: the share of the collateral value that counts towards
   * covering debt.
   *
   * @example `9000` for an 86% threshold
   **/
  liquidationThreshold: Bps;
  /**
   * Share of a liquidated account's value paid to the liquidator, in basis
   * points.
   *
   * @example `400` for a 4% premium
   **/
  liquidationPremium: Bps;
  /**
   * Share of a liquidated account's value taken by the protocol, in basis
   * points.
   *
   * @example `150` for a 1.5% fee
   **/
  liquidationFee: Bps;
  /**
   * Moment the credit facade expires, after which positions can no longer be
   * opened and open ones become liquidatable, or `null` when the facade is not
   * expirable. A timestamp in the past means it has already expired.
   **/
  expirationDate: Timestamp | null;
  /**
   * Yield the collateral itself earns while it sits in the credit account,
   * before leverage. Comes from external sources rather than from the chain.
   *
   * @mode offchain
   **/
  collateralApy?: ApyBreakdown;
  /**
   * Average {@link collateralApy} over the trailing seven days.
   *
   * @mode offchain
   **/
  collateralApyAvg7D?: ApyBreakdown;
  /**
   * Net yield at {@link maxLeverage}:
   * `collateralApy × maxLeverage − borrowApy × (maxLeverage − 1) − additionalBorrowApy`.
   * Yield is on the whole position; borrow interest is on the borrowed part only.
   *
   * Absent in `onchain` mode: its {@link collateralApy} term is.
   *
   * @mode offchain
   **/
  maxLeverageApy?: ApyBreakdown;
  /**
   * Average {@link maxLeverageApy} over the trailing seven days.
   *
   * @mode offchain
   **/
  maxLeverageApyAvg7D?: ApyBreakdown;
  /**
   * Annual cost of the borrowed underlying, in basis points, including the
   * protocol's interest fee.
   *
   * @example `520` for 5.2% APY
   **/
  borrowApy?: Bps;
  /**
   * Average {@link borrowApy} over the trailing seven days, in basis points.
   *
   * Absent in `onchain` mode: calculating it requires historical data.
   *
   * @mode offchain
   **/
  borrowApyAvg7D?: Bps;
  /**
   * Annual cost of the quota on {@link targetCollateral}, in basis points:
   * `quotaRate × (1 + feeInterest) × maxLeverage`. Quota accrues on the whole
   * quoted position and carries the same DAO fee as {@link borrowApy}.
   *
   * @example `90` for +0.9% APY
   **/
  additionalBorrowApy?: Bps;
  /**
   * Average {@link additionalBorrowApy} over the trailing seven days, in basis
   * points.
   *
   * Absent in `onchain` mode: calculating it requires historical data.
   *
   * @mode offchain
   **/
  additionalBorrowApyAvg7D?: Bps;
  /**
   * Size of the strategy: the summed total value of the credit accounts
   * holding {@link targetCollateral}. An account that holds several strategy
   * collaterals counts in full towards each of them.
   *
   * Absent in `onchain` mode.
   *
   * @mode offchain
   **/
  totalValue?: Amount;
  /**
   * Share of {@link totalValue} that is borrowed, in basis points:
   * `totalBorrow / totalValue`.
   *
   * Absent in `onchain` mode, because its denominator is, see
   * {@link totalValue}.
   *
   * @example `7500` for 75% utilization
   *
   * @mode offchain
   **/
  utilization?: Bps;
  /**
   * Free liquidity of the pool the strategy borrows from, denominated in the
   * underlying. Same value the market's {@link PoolOpportunity} reports.
   **/
  availableLiquidity: Amount;
  /**
   * Smallest debt a position in this credit manager may hold, denominated in
   * the underlying (`creditFacade.minDebt`).
   **/
  minDebt: Amount;
  /**
   * Cap on the total debt this credit manager may draw from the pool, shared
   * by all of its accounts and denominated in the underlying
   * (`creditManagerDebtParams.limit`).
   **/
  totalDebtLimit: Amount;
  /**
   * Largest debt a single new position can take on right now: the tightest of
   * the credit manager's remaining debt limit, the pool's free liquidity and
   * the facade's per-account maximum.
   **/
  maxBorrowAmount: Amount;
  /**
   * Highest total-value leverage the liquidation threshold allows:
   * `(1 − 0.05) / (1 − liquidationThreshold)`. The 5% safety margin keeps a
   * maxed position slightly above HF = 1.
   *
   * @example `9.5` at a 90% threshold
   **/
  maxLeverage: Leverage;
}

/**
 * A row of the opportunities list.
 **/
export type Opportunity = PoolOpportunity | StrategyOpportunity;

/**
 * Canonical id of an opportunity: the string used to match a row read from the
 * chain with the same row served by the backend.
 **/
export type OpportunityId = string;

/**
 * Builds the canonical id of a pool opportunity.
 *
 * @example
 * ```ts
 * poolOpportunityId(1, "0xda00...") // "1:0xda00..."
 * ```
 **/
export function poolOpportunityId(
  chainId: ChainId,
  pool: Address,
): OpportunityId {
  return `${chainId}:${pool.toLowerCase()}`;
}

/**
 * Builds the canonical id of a strategy opportunity.
 *
 * @example
 * ```ts
 * strategyOpportunityId(1, "0x3eb9...", "0x7f39...") // "1:0x3eb9...:0x7f39..."
 * ```
 **/
export function strategyOpportunityId(
  chainId: ChainId,
  creditManager: Address,
  targetCollateral: Address,
): OpportunityId {
  return `${chainId}:${creditManager.toLowerCase()}:${targetCollateral.toLowerCase()}`;
}

/**
 * Canonical id of any opportunity, dispatching on {@link Opportunity.kind}.
 **/
export function opportunityId(opportunity: Opportunity): OpportunityId {
  return opportunity.kind === "pool"
    ? poolOpportunityId(opportunity.chainId, opportunity.pool)
    : strategyOpportunityId(
        opportunity.chainId,
        opportunity.creditManager,
        opportunity.targetCollateral.address,
      );
}

/**
 * Optional narrowing of an opportunities list.
 *
 * The list is filtered in memory over final values, so there is no paging and
 * no sorting: a screen sorts what it got.
 *
 * Every condition is optional and an omitted one matches any value, so an
 * empty filter is the same as no filter at all. A condition can also be set to
 * `"all"` to say the same thing explicitly, which is what a UI whose state has
 * an "any" option holds, see {@link Filterable}. Conditions combine with AND.
 **/
export interface OpportunityFilter extends ChainScopedFilter {
  /**
   * Keep only pools or only strategies.
   **/
  kind?: Filterable<OpportunityKind>;
  /**
   * Keep only opportunities whose {@link OpportunityBase.underlyingToken} is of
   * this class, which for an RWA market means the class of the token its
   * wrapper holds. An underlying that is not in the hardcoded table never
   * matches, so a set filter also drops unclassified rows.
   **/
  underlyingType?: Filterable<AssetType>;
  /**
   * Keep only paused opportunities, or only unpaused ones.
   **/
  paused?: Filterable<boolean>;
  /**
   * Keep only opportunities being wound down, or only the ones that are not.
   **/
  sunset?: Filterable<boolean>;
  /**
   * Keep only opportunities that accept RWA collateral, or only the ones that
   * do not.
   **/
  rwa?: Filterable<boolean>;
}

/**
 * Whether an opportunity satisfies every condition of a filter.
 *
 * This is the single definition of what each condition means: every source
 * builds its rows first and runs them through here, so the chain and the
 * backend cannot disagree on what a filter selects.
 *
 * @param opportunity - Row to test.
 * @param filter - Conditions to test against. An absent filter matches
 * anything.
 **/
export function matchesOpportunityFilter(
  opportunity: Opportunity,
  filter?: OpportunityFilter,
): boolean {
  if (!filter) {
    return true;
  }
  if (isFilterSet(filter.kind) && opportunity.kind !== filter.kind) {
    return false;
  }
  if (filter.chainIds && !filter.chainIds.includes(opportunity.chainId)) {
    return false;
  }
  if (
    isFilterSet(filter.underlyingType) &&
    opportunity.underlyingToken.assetType !== filter.underlyingType
  ) {
    return false;
  }
  if (isFilterSet(filter.paused) && opportunity.paused !== filter.paused) {
    return false;
  }
  if (isFilterSet(filter.sunset) && opportunity.sunset !== filter.sunset) {
    return false;
  }
  if (isFilterSet(filter.rwa) && opportunity.rwa !== filter.rwa) {
    return false;
  }
  return true;
}

/**
 * One point of an interest rate curve.
 **/
export interface RateCurvePoint {
  /**
   * Utilization this point is sampled at, in basis points.
   *
   * @example `9000` for 90% utilization
   **/
  utilization: Bps;
  /**
   * Rate depositors earn at this utilization, in basis points.
   *
   * @example `430` for 4.3%
   **/
  supplyApy: Bps;
  /**
   * Base rate borrowers pay at this utilization, in basis points. Excludes the
   * per-credit-manager interest fee, because the curve belongs to the pool and
   * every credit manager of a market can charge a different one.
   *
   * @example `620` for 6.2%
   **/
  borrowApy: Bps;
}

/**
 * The pool's interest rate model, evaluated into chart-ready points so that no
 * consumer has to reimplement the model.
 **/
export interface RateCurve {
  /**
   * Points ordered by ascending utilization, always including the kinks of the
   * model so the polyline is exact rather than approximated.
   **/
  points: RateCurvePoint[];
  /**
   * Utilization above which borrowing is forbidden, in basis points, or `null`
   * when the model has no such cutoff.
   *
   * @example `9000` for a cutoff at 90% utilization
   **/
  borrowingLimitUtilization: Bps | null;
}

/**
 * Quota configuration of one collateral token: how much of it the market
 * accepts in total, and what holding it costs.
 **/
export interface QuotaAsset {
  /**
   * Token the quota applies to.
   **/
  token: Token;
  /**
   * Annual quota rate paid on the quoted amount, in basis points.
   *
   * @example `250` for 2.5% per year
   **/
  quotaRate: Bps;
  /**
   * Maximum amount that can be quoted across all credit accounts, denominated
   * in the market's underlying.
   **/
  limit: Amount;
  /**
   * Amount currently quoted, denominated in the market's underlying.
   **/
  used: Amount;
}

/**
 * A price feed and the feeds it is composed of.
 **/
export interface PriceFeedData {
  /**
   * Display name of the feed.
   *
   * @example `"CompositePriceFeed wstETH / USD"`
   **/
  name: string;
  /**
   * Gearbox price feed contract type.
   *
   * @example `"PRICE_FEED::COMPOSITE"`, `"PRICE_FEED::REDSTONE"`
   **/
  type: string;
  /**
   * Address of the feed contract.
   **/
  feedAddress: Address;
  /**
   * Feeds this feed reads from. Empty for a leaf feed.
   **/
  dependencies: PriceFeedData[];
}

/**
 * Prices and feeds behind a strategy, i.e. everything a liquidation-price chart
 * needs.
 **/
export interface PriceFeedSummary {
  /**
   * Price of one whole underlying token in USD.
   *
   * @example `1.0001` for USDC
   **/
  underlyingPriceInUsd: number;
  /**
   * Price of one whole collateral token in USD.
   *
   * @example `4210.55` for wstETH
   **/
  collateralPriceInUsd: number;
  /**
   * Price of one whole collateral token expressed in the underlying.
   *
   * @example `4210.13` for wstETH priced in USDC
   **/
  collateralPriceInUnderlying: number;
  /**
   * Main feed of the underlying token.
   **/
  underlyingFeed: PriceFeedData;
  /**
   * Main feed of the collateral token. Reserve feeds are not included.
   **/
  collateralFeed: PriceFeedData;
}

/**
 * A pool opportunity plus the data only its detail screen needs.
 **/
export interface PoolOpportunityDetail extends PoolOpportunity {
  /**
   * Interest rate curve of the pool.
   **/
  rateCurve: RateCurve;
  /**
   * Quota configuration of every collateral token of the market.
   **/
  quotaAssets: QuotaAsset[];
}

/**
 * A strategy opportunity plus the data only its detail screen needs.
 **/
export interface StrategyOpportunityDetail extends StrategyOpportunity {
  /**
   * Interest rate curve of the pool the strategy borrows from.
   **/
  rateCurve: RateCurve;
  /**
   * Prices and feeds of the underlying and the target collateral.
   **/
  priceFeeds: PriceFeedSummary;
}

/**
 * Detailed view of any opportunity.
 **/
export type OpportunityDetail =
  | PoolOpportunityDetail
  | StrategyOpportunityDetail;

/**
 * Identifies a pool opportunity in a detail request.
 **/
export interface PoolOpportunityKey {
  chainId: ChainId;
  pool: Address;
}

/**
 * Identifies a strategy opportunity in a detail request.
 **/
export interface StrategyOpportunityKey {
  chainId: ChainId;
  creditManager: Address;
  /**
   * Address of the target collateral token.
   **/
  targetCollateral: Address;
}

/**
 * {@link PoolOpportunityKey} tagged with its kind, for requests that accept
 * both kinds.
 **/
export interface PoolOpportunityRef extends PoolOpportunityKey {
  kind: "pool";
}

/**
 * {@link StrategyOpportunityKey} tagged with its kind, for requests that accept
 * both kinds.
 **/
export interface StrategyOpportunityRef extends StrategyOpportunityKey {
  kind: "strategy";
}

/**
 * Identifies any opportunity, for requests that accept both kinds.
 **/
export type OpportunityKey = PoolOpportunityRef | StrategyOpportunityRef;
